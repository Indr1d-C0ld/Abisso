function withFamous(f: Famous): Boat {
  const base = BOATS.find((b) => b.id === f.base);
  if (!base) throw new Error(f.base);
  return {
    ...base,
    id: f.id,
    name: f.name,
    historical: true,
    blurb: f.blurb,
    fate: f.fate,
    sources: base.sources,
  };
}

export const ALL_BOATS: Boat[] = [...BOATS, ...FAMOUS.map(withFamous)];

export function boatById(id: string) {
  return ALL_BOATS.find((b) => b.id === id) ?? ALL_BOATS.find((b) => b.id === "vii-c")!;
}

